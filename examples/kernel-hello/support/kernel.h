#ifndef PLUM_FREESTANDING_X86_64_KERNEL_H
#define PLUM_FREESTANDING_X86_64_KERNEL_H

#include <stdint.h>

#define PLUM_KERNEL_HEAP_BYTES (1024u * 1024u)

/* One CPU, interrupts disabled, mapped/zero-filled BSS, initialized x87/SSE,
 * and a System V aligned stack are prerequisites for all of these functions.
 * Call init before plum_kernel_start. Repeated init never resets the arena. */
void plum_kernel_runtime_init(void);
void *plum_kernel_alloc(uint64_t size);
/* Bounded boot-demo policy: no reclamation, including for NULL. */
void plum_kernel_free(void *allocation);
/* Borrowed bytes: valid for length bytes; NULL is allowed for zero length. */
void plum_kernel_write(const uint8_t *data, uint64_t length);
_Noreturn void plum_kernel_panic(const uint8_t *data, uint64_t length);
_Noreturn void plum_kernel_halt(void);

/* Generated by Plum, not implemented by this support library. */
_Noreturn void plum_kernel_start(void);

#endif
