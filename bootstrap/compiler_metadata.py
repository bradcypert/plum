"""Validated compiler facts shared by bootstrap tools and generated Plum."""
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "bootstrap/compiler-metadata.json"
OUTPUT = ROOT / "bootstrap/self_host/compiler_metadata/compiler_metadata.plum"
NUMBER = r"(?:0|[1-9][0-9]*)"
PRERELEASE = r"(?:0|[1-9][0-9]*|[0-9]*[A-Za-z-][0-9A-Za-z-]*)"
VERSION = re.compile(
    rf"{NUMBER}\.{NUMBER}\.{NUMBER}(?:-{PRERELEASE}(?:\.{PRERELEASE})*)?"
    r"(?:\+[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?"
)


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate metadata key: {key}")
        result[key] = value
    return result


def load(path=SOURCE):
    data = json.loads(Path(path).read_text(encoding="utf-8"), object_pairs_hook=unique_object)
    if not isinstance(data, dict) or set(data) != {"schema_version", "version", "stdlib_modules"}:
        raise ValueError("expected schema_version, version, and stdlib_modules")
    if type(data["schema_version"]) is not int or data["schema_version"] != 1:
        raise ValueError("unsupported compiler metadata schema_version")
    version = data["version"]
    if not isinstance(version, str) or not VERSION.fullmatch(version):
        raise ValueError("invalid compiler version")
    modules = data["stdlib_modules"]
    if not isinstance(modules, list) or not modules or any(
        not isinstance(m, str) or not re.fullmatch(r"[A-Z][A-Za-z0-9_]*", m) for m in modules
    ):
        raise ValueError("stdlib_modules must be a nonempty array of module names")
    if len(set(modules)) != len(modules):
        raise ValueError("duplicate stdlib_modules entry")
    return data


def render(data):
    # No compiler is required to regenerate bootstrap inputs. CI checks the
    # generated source against both this renderer and the default formatter.
    names = ",\n".join("        " + json.dumps(m) for m in data["stdlib_modules"])
    flat = "[" + ", ".join(json.dumps(m) for m in data["stdlib_modules"]) + "]"
    array = "    " + flat + "\n" if len(flat) + 4 <= 100 else "    [\n" + names + "\n    ]\n"
    return (
        "// GENERATED by bootstrap/gen-compiler-metadata from bootstrap/compiler-metadata.json.\n"
        "// Edit the JSON and regenerate; bootstrap tools read that same validated metadata.\n\n"
        f'pub let version (): String = {json.dumps(data["version"])}\n\n'
        "pub let std_module_names (): Array[String] =\n" + array
    )


def check_generated(data, output=OUTPUT):
    if not output.exists() or output.read_text(encoding="utf-8") != render(data):
        raise ValueError("compiler metadata declarations are stale -- run bootstrap/gen-compiler-metadata")


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("field", choices=["version", "stdlib_modules"])
    args = ap.parse_args()
    try:
        data = load()
        check_generated(data)
    except (OSError, ValueError) as error:
        ap.exit(1, f"compiler metadata: {error}\n")
    value = data[args.field]
    print("\n".join(value) if isinstance(value, list) else value)
